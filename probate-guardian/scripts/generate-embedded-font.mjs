#!/usr/bin/env node
/**
 * scripts/generate-embedded-font.mjs
 *
 * Sourcing & subsetting pipeline for Probate Guardian PDF TrueType font embedding (Milestone 19-5).
 * Slices Liberation Sans (SIL Open Font License 1.1) Regular, Bold, and Italic into minimal
 * Latin + typographic subsets, converting them to Base64 strings in src/assets/embedded-fonts.js.
 *
 * Source: Liberation Sans v2.1.5
 * URL: https://github.com/liberationfonts/liberation-fonts/files/7261482/liberation-fonts-ttf-2.1.5.tar.gz
 *
 * Usage:
 *   node scripts/generate-embedded-font.mjs
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import subsetFont from 'subset-font';
import { fontCodePoints, toRanges } from './ttf-cmap.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const fontsSrcDir = path.join(root, 'fonts-src');
const outputFile = path.join(root, 'src', 'assets', 'embedded-fonts.js');
const printableFile = path.join(root, 'src', 'core', 'pdf', 'printable-chars.js');

const LIBERATION_TAR_URL =
  'https://github.com/liberationfonts/liberation-fonts/files/7261482/liberation-fonts-ttf-2.1.5.tar.gz';

async function main() {
  console.log('[generate-embedded-font] Preparing font source directory...');
  await fs.mkdir(fontsSrcDir, { recursive: true });

  const tarPath = path.join(fontsSrcDir, 'liberation-fonts.tar.gz');
  const extractedFolder = path.join(fontsSrcDir, 'liberation-fonts-ttf-2.1.5');

  try {
    await fs.access(extractedFolder);
    console.log('[generate-embedded-font] Found existing extracted font files.');
  } catch {
    console.log(`[generate-embedded-font] Downloading Liberation Sans from ${LIBERATION_TAR_URL}...`);
    const res = await fetch(LIBERATION_TAR_URL);
    if (!res.ok) throw new Error(`Download failed with status ${res.status}`);
    const buffer = Buffer.from(await res.arrayBuffer());
    await fs.writeFile(tarPath, buffer);

    console.log('[generate-embedded-font] Extracting font archive...');
    const tarResult = spawnSync('tar', ['-xzf', tarPath, '-C', fontsSrcDir]);
    if (tarResult.status !== 0) {
      throw new Error(`tar extraction failed: ${tarResult.stderr?.toString()}`);
    }
  }

  // Define glyph subset string
  let glyphs = '';
  // Basic Latin (ASCII 0x20 .. 0x7E)
  for (let i = 0x20; i <= 0x7E; i++) glyphs += String.fromCharCode(i);
  // Latin-1 Supplement (0xA0 .. 0xFF) - covers legal names with accents (Álvarez, Peña) & symbols ($, §, ©, ®, °, etc.)
  for (let i = 0xA0; i <= 0xFF; i++) glyphs += String.fromCharCode(i);
  // Milestone 76H item 4 (decision 76H-1): Latin Extended-A and -B (0x100 ..
  // 0x24F) -- Dvořák, Łukasz, Żółć, Ştefan. Letters the font lacked were
  // dropped from the PDF without a word ("Dvořák" printed "Dvoák"). Whatever
  // Liberation Sans itself lacks in these blocks is left out by the subsetter
  // and so is not in printable-chars.js either.
  for (let i = 0x100; i <= 0x24F; i++) glyphs += String.fromCharCode(i);
  // Typographic extras & currency: en/em dash, curly quotes, bullet, ellipsis, per mille, trademark, minus, checkmarks, euro
  glyphs += '–—‘’“”•…‰™−✓✔☑☐€';

  console.log(`[generate-embedded-font] Subsetting ${glyphs.length} glyphs...`);

  const fontConfigs = [
    {
      exportName: 'PG_SANS_REGULAR_B64',
      fileName: 'LiberationSans-Regular.ttf',
      style: 'normal',
    },
    {
      exportName: 'PG_SANS_BOLD_B64',
      fileName: 'LiberationSans-Bold.ttf',
      style: 'bold',
    },
    {
      exportName: 'PG_SANS_ITALIC_B64',
      fileName: 'LiberationSans-Italic.ttf',
      style: 'italic',
    },
  ];

  const results = {};
  /** @type {number[][]} */
  const faces = [];

  for (const cfg of fontConfigs) {
    const srcPath = path.join(extractedFolder, cfg.fileName);
    const rawTtf = await fs.readFile(srcPath);
    console.log(`[generate-embedded-font] Subsetting ${cfg.fileName} (${rawTtf.length} bytes raw)...`);
    const subsetBuffer = await subsetFont(rawTtf, glyphs, { targetFormat: 'truetype' });
    faces.push(fontCodePoints(new Uint8Array(subsetBuffer)));
    const b64 = subsetBuffer.toString('base64');
    console.log(`  -> Subsetted size: ${subsetBuffer.length} bytes (Base64: ${b64.length} chars)`);
    results[cfg.exportName] = b64;
  }

  const fileContent = `/**
 * src/assets/embedded-fonts.js
 *
 * Generated by scripts/generate-embedded-font.mjs (Milestone 19-5).
 * Contains Base64-encoded TrueType font subsets for Liberation Sans (v2.1.5).
 * Licensed under the SIL Open Font License 1.1 (see src/assets/LICENSE-LiberationSans.txt).
 *
 * Family: PGSans
 * Faces: Regular, Bold, Italic
 *
 * DO NOT EDIT MANUALLY. Regenerate using: npm run generate:fonts
 */

export const PG_SANS_REGULAR_B64 = '${results.PG_SANS_REGULAR_B64}';

export const PG_SANS_BOLD_B64 = '${results.PG_SANS_BOLD_B64}';

export const PG_SANS_ITALIC_B64 = '${results.PG_SANS_ITALIC_B64}';
`;

  await fs.writeFile(outputFile, fileContent, 'utf8');
  console.log(`[generate-embedded-font] Wrote ${outputFile} successfully.`);

  // Milestone 76H item 4: the characters every face can draw (a heading prints
  // in bold, a note in italic), for the on-screen note about a letter the PDF
  // would leave out. Read from the fonts just written, never from the list
  // asked for above.
  const printable = faces.reduce((a, b) => a.filter((p) => b.includes(p)));
  const hex = (n) => `0x${n.toString(16).toUpperCase().padStart(4, '0')}`;
  const printableContent = `/**
 * src/core/pdf/printable-chars.js
 *
 * Generated by scripts/generate-embedded-font.mjs (Milestone 76H item 4) from
 * the character maps of the fonts in src/assets/embedded-fonts.js: the
 * characters all three faces can draw, as [first, last] runs. A character
 * outside them is left out of the PDF. tests/unit/printable-chars.spec.js
 * holds this list to the fonts.
 *
 * DO NOT EDIT MANUALLY. Regenerate using: npm run generate:fonts
 */

export const PRINTABLE_RANGES = Object.freeze([
${toRanges(printable).map(([a, b]) => `  [${hex(a)}, ${hex(b)}],`).join('\n')}
]);
`;
  await fs.writeFile(printableFile, printableContent, 'utf8');
  console.log(`[generate-embedded-font] Wrote ${printableFile}: ${printable.length} characters.`);
}

main().catch((err) => {
  console.error('[generate-embedded-font] Error:', err);
  process.exit(1);
});
